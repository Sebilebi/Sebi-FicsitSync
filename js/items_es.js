/**
 * Normalizes an item key (e.g. Desc_IronPlate_C, IronPlate, Iron_Plate) and returns its official Spanish name.
 */
function getItemNameEs(itemKey) {
  if (!itemKey) return 'Ítem Desconocido';
  if (ITEM_NAMES_ES[itemKey]) return ITEM_NAMES_ES[itemKey];

  // Clean Unreal prefixes/suffixes
  let clean = itemKey.replace(/^Desc_/, '').replace(/_C$/, '');
  if (ITEM_NAMES_ES[clean]) return ITEM_NAMES_ES[clean];

  // Handle camelCase to Snake_Case (e.g. IronPlate -> Iron_Plate)
  const snake = clean.replace(/([a-z0-9])([A-Z])/g, '$1_$2');
  if (ITEM_NAMES_ES[snake]) return ITEM_NAMES_ES[snake];

  // Handle Ore prefix (OreIron -> Iron_Ore)
  if (clean.startsWith('Ore')) {
    const res = clean.replace('Ore', '') + '_Ore';
    if (ITEM_NAMES_ES[res]) return ITEM_NAMES_ES[res];
  }

  // Handle direct lookups without underscore
  const noUnderscore = clean.replace(/_/g, '').toLowerCase();
  for (const [k, v] of Object.entries(ITEM_NAMES_ES)) {
    if (k.replace(/_/g, '').toLowerCase() === noUnderscore) return v;
  }

  return clean.replace(/_/g, ' ');
}

